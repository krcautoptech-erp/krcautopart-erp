function searchableGuideText(guide: HelpGuide) {
  return [
    guide.title,
    guide.purpose,
    ...guide.keywords,
    ...guide.prerequisites,
    ...guide.steps.flatMap((step) => [step.title, step.detail]),
    ...guide.reference.flatMap((item) => [item.term, item.detail]),
    ...guide.completion,
    ...guide.troubleshooting,
  ].join(" ").toLocaleLowerCase("th");
}

export function filterHelpGuides(
  query = "",
  permissions?: readonly string[],
  isOwner = false,
): readonly HelpGuide[] {
  const permissionSet = new Set(permissions ?? []);
  const accessibleGuides = permissions === undefined || isOwner
    ? HELP_GUIDES
    : HELP_GUIDES.filter((guide) => {
        const required = HELP_GUIDE_PERMISSIONS[guide.id];
        return !required || required.some((permission) => permissionSet.has(permission));
      });
  const needle = query.trim().toLocaleLowerCase("th");
  return needle
    ? accessibleGuides.filter((guide) => searchableGuideText(guide).includes(needle))
    : accessibleGuides;
}

export function getHelpGuide(pathname: string, search = "") {
  const params = new URLSearchParams(search.startsWith("?") ? search.slice(1) : search);
  if (pathname === "/settings/roles" || (pathname === "/settings/users" && params.get("tab") === "roles")) {
    return HELP_GUIDES.find((guide) => guide.id === "roles")!;
  }

  const match = HELP_GUIDES
    .flatMap((guide) => guide.routes.map((route) => ({ guide, route })))
    .filter(({ route }) => pathname === route || (route !== "/" && pathname.startsWith(`${route}/`)))
    .sort((a, b) => b.route.length - a.route.length)[0];

  return match?.guide ?? HELP_GUIDES.find((guide) => guide.id === "general")!;
}
