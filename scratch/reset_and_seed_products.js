async function seed() {
  try {
    await client.connect();
    console.log("Connected to PostgreSQL.");

    // 1. Drop the unique constraint on part_number to allow duplicate part numbers
    console.log("Dropping unique constraint products_part_number_key if it exists...");
    await client.query(`
      ALTER TABLE public.products DROP CONSTRAINT IF EXISTS products_part_number_key;
      ALTER TABLE public.products DROP CONSTRAINT IF EXISTS products_part_number_unique;
    `);

    // 2. Clear all existing products
    console.log("Truncating products table...");
    await client.query("TRUNCATE TABLE public.products CASCADE;");
    console.log("Products table cleared.");

    // 3. Parse input data
    const lines = rawData.trim().split("\n");
    const productsToInsert = [];
    const seen = new Set();

    lines.forEach((line, idx) => {
      const trimmed = line.trim();
      if (!trimmed) return;
      
      // Split by tab or consecutive spaces
      const parts = trimmed.split(/\t|\s{2,}/);
      if (parts.length >= 3) {
        const erp_code = parts[0].trim();
        const part_name = parts[1].trim();
        const part_number = parts[2].trim();
        
        // Skip duplicate records in the input list
        const key = `${erp_code}|||${part_number}`;
        if (!seen.has(key)) {
          seen.add(key);
          productsToInsert.push({ erp_code, part_name, part_number });
        }
      } else {
        console.warn(`Warning: line ${idx + 1} did not parse correctly: "${line}"`);
      }
    });

    console.log(`Parsed ${productsToInsert.length} unique products to seed.`);

    // 4. Insert records
    let inserted = 0;
    for (const prod of productsToInsert) {
      await client.query(
        `INSERT INTO public.products (
          part_number, part_name, erp_code, cost_price, selling_price, unit, status
        ) VALUES ($1, $2, $3, 0, 0, 'ชิ้น', 'ใช้งาน')`,
        [prod.part_number, prod.part_name, prod.erp_code]
      );
      inserted++;
    }

    console.log(`Seeded ${inserted} products successfully.`);
  } catch (err) {
    console.error("Seeding failed:", err);
  } finally {
    await client.end();
  }
}

